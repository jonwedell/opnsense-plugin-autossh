namespace ThreatPatrols\Autossh\Api;

use OPNsense\Base\ApiMutableModelControllerBase;
use OPNsense\Base\UserException;
use OPNsense\Core\Backend;

class KeysController extends ApiMutableModelControllerBase
{
    protected static $internalModelName = 'autossh';
    protected static $internalModelClass = 'ThreatPatrols\Autossh\Autossh';

    /**
     * Restrictions prepended to the public key when it is handed out for
     * installation on the remote: the key may forward ports and nothing else.
     */
    private const KEY_RESTRICTIONS = 'command="",no-agent-forwarding,no-pty,no-user-rc,no-X11-forwarding';

    public function searchKeyAction()
    {
        return $this->searchBase('keys.key', ['name', 'type', 'key_fingerprint', 'description'], 'name');
    }

    public function getKeyAction($uuid = null)
    {
        return $this->getBase('key', 'keys.key', $uuid);
    }

    /**
     * Key material is generated by the backend rather than supplied by the
     * client, and overlaid onto the posted record.
     */
    public function addKeyAction()
    {
        if (!$this->request->isPost() || !$this->request->hasPost('key')) {
            return ['result' => 'failed'];
        }

        $posted = $this->request->getPost('key');
        $key_type = $posted['type'] ?? 'ed25519';

        $generated = json_decode(
            trim((new Backend())->configdpRun('autossh keygen', [$key_type])),
            true
        );

        if (empty($generated) || ($generated['status'] ?? '') !== 'success') {
            return [
                'result' => 'failed',
                'validations' => [
                    'key.type' => $generated['message'] ?? gettext('Key generation failed, review the configd log.'),
                ],
            ];
        }

        return $this->addBase('key', 'keys.key', $generated['data']);
    }

    /**
     * Only the name and description are editable; the key type and material
     * are pinned to what was generated.
     */
    public function setKeyAction($uuid)
    {
        $node = $this->getModel()->getNodeByReference('keys.key.' . $uuid);
        if ($node === null) {
            return ['result' => 'failed'];
        }

        return $this->setBase('key', 'keys.key', $uuid, [
            'type' => (string)$node->type,
            'key_private' => (string)$node->key_private,
            'key_public' => (string)$node->key_public,
            'key_fingerprint' => (string)$node->key_fingerprint,
            'timestamp' => (string)$node->timestamp,
        ]);
    }

    public function delKeyAction($uuid)
    {
        foreach ($this->getModel()->tunnels->tunnel->iterateItems() as $tunnel) {
            if ((string)$tunnel->ssh_key !== $uuid) {
                continue;
            }

            $label = (string)$tunnel->description;
            if (empty($label)) {
                $label = (string)$tunnel->user . '@' . (string)$tunnel->hostname;
            }

            throw new UserException(
                sprintf(
                    gettext('This key cannot be removed, it is still used by tunnel "%s".'),
                    $label
                ),
                gettext('Autossh')
            );
        }

        return $this->delBase('keys.key', $uuid);
    }

    /**
     * Backs the grid's info button: hand out the public key in authorized_keys
     * form, restrictions included, ready to paste onto the remote host.
     */
    public function infoAction($uuid)
    {
        $info = [
            'title' => gettext('Public key for the remote authorized_keys file'),
            'message' => gettext('Unknown ssh key.'),
        ];

        $node = $this->getModel()->getNodeByReference('keys.key.' . $uuid);
        if ($node === null) {
            return $info;
        }

        $public_key = trim(base64_decode((string)$node->key_public));
        if (empty($public_key)) {
            $info['message'] = gettext('This key holds no public key material.');
            return $info;
        }

        // the generated comment records the system hostid; replace it with
        // something that identifies this key record instead
        $public_key = preg_replace('/host_id:.*?$/', 'autossh_key_id:' . $uuid, $public_key);

        // plain text only: the dialog escapes whatever it is handed
        $info['message'] = self::KEY_RESTRICTIONS . ' ' . $public_key;

        return $info;
    }
}
