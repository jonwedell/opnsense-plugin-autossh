namespace ThreatPatrols\Autossh;

use OPNsense\Base\BaseModel;
use OPNsense\Base\Messages\Message;

class Autossh extends BaseModel
{
    /**
     * A tunnel that forwards nothing connects and then sits idle, which is
     * almost never what was intended -- require at least one forward or an
     * explicit layer 2/3 tunnel.
     */
    private function checkTunnelHasPurpose($messages, $validateFullModel)
    {
        foreach ($this->tunnels->tunnel->iterateItems() as $tunnel) {
            if (!$validateFullModel && !$tunnel->isFieldChanged()) {
                continue;
            }

            $forwards = [
                (string)$tunnel->local_forward,
                (string)$tunnel->remote_forward,
                (string)$tunnel->dynamic_forward,
            ];

            if (
                empty(array_filter($forwards)) &&
                (string)$tunnel->tunnel === 'no'
            ) {
                $messages->appendMessage(new Message(
                    gettext(
                        'Provide at least one of Local forward, Remote forward, Dynamic forward, ' .
                        'or select a Tunnel device mode.'
                    ),
                    $tunnel->__reference . '.local_forward'
                ));
            }
        }
    }

    /**
     * A tunnel device mode without a device specification cannot be rendered.
     */
    private function checkTunnelDevice($messages, $validateFullModel)
    {
        foreach ($this->tunnels->tunnel->iterateItems() as $tunnel) {
            if (!$validateFullModel && !$tunnel->isFieldChanged()) {
                continue;
            }
            if ((string)$tunnel->tunnel !== 'no' && empty((string)$tunnel->tunnel_device)) {
                $messages->appendMessage(new Message(
                    gettext('A tunnel device is required when a tunnel mode is selected, e.g. "any:any".'),
                    $tunnel->__reference . '.tunnel_device'
                ));
            }
        }
    }

    /**
     * Keys are generated by the backend; a key record without material is unusable
     * and would render a tunnel that cannot authenticate.
     */
    private function checkKeyMaterial($messages, $validateFullModel)
    {
        foreach ($this->keys->key->iterateItems() as $key) {
            if (!$validateFullModel && !$key->isFieldChanged()) {
                continue;
            }
            if (empty((string)$key->key_private) || empty((string)$key->key_public)) {
                $messages->appendMessage(new Message(
                    gettext('This key holds no key material; delete it and generate a new key.'),
                    $key->__reference . '.name'
                ));
            }
        }
    }

    /**
     * Like the field level checks in BaseModel, the record level checks only
     * look at records that changed unless a full validation is requested.
     * serializeToConfig() refuses to save on any message at all, so checking
     * every record would let one pre-existing bad record -- e.g. carried over
     * from the original plugin -- block every save, toggle and key addition.
     */
    public function performValidation($validateFullModel = false)
    {
        $messages = parent::performValidation($validateFullModel);

        $this->checkTunnelHasPurpose($messages, $validateFullModel);
        $this->checkTunnelDevice($messages, $validateFullModel);
        $this->checkKeyMaterial($messages, $validateFullModel);

        return $messages;
    }
}
