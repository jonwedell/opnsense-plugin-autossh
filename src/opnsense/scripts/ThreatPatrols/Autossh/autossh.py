# ssh client configuration generation


def resolve_mapped(field, stored_value, mappings):
    """Resolve a stored algorithm list to a comma separated algorithm list.

    Accepts the algorithm name (what the model stores) as well as the
    element-name placeholder, so that a configuration written by the original
    plugin's 0.3.0 migration still renders the algorithms it intended.
    """
    table = mappings.get(field, {})
    known_values = set(table.values())

    resolved = []
    for option in [v.strip() for v in (stored_value or "").split(",") if v.strip()]:
        if option in table:
            resolved.append(table[option])
        elif option in known_values:
            resolved.append(option)
        else:
            log_warn(f"ignoring unknown {field} option '{option}'")

    return ",".join(resolved)


def render_tunnel(uuid, tunnel, mappings, interfaces):
    """Render one Host block. Returns a string."""
    identity = os.path.join(STATE_DIR, f"{uuid}.identity")
    known_hosts = os.path.join(STATE_DIR, f"{uuid}.known_hosts")
    info_file = os.path.join(RUN_DIR, f"autossh.{uuid}.info")

    bind_interface = tunnel.get("bind_interface", "")
    bind_device = interfaces.get(bind_interface, bind_interface)

    lines = [f"Host {uuid}"]

    if tunnel.get("description"):
        lines.append(f"    # {tunnel['description']}")

    def put(option, value):
        if value not in (None, ""):
            lines.append(f"    {option} {value}")

    put("AddKeysToAgent", "no")
    put("AddressFamily", tunnel.get("address_family", "any"))
    put("BatchMode", "yes")
    put("BindInterface", bind_device)
    put("CanonicalizeHostname", "no")
    put("CheckHostIP", tunnel.get("check_host_ip", "no"))
    put("Ciphers", resolve_mapped("ciphers", tunnel.get("ciphers"), mappings))
    put("ClearAllForwardings", "no")
    put("Compression", tunnel.get("compression", "no"))
    put("ConnectionAttempts", tunnel.get("connection_attempts", "5"))
    put("ConnectTimeout", tunnel.get("connect_timeout", "15"))
    put("ControlMaster", "no")
    put("ControlPath", "none")
    put("ControlPersist", "no")
    put("DynamicForward", tunnel.get("dynamic_forward"))
    put("EnableSSHKeysign", "no")
    put("ExitOnForwardFailure", "yes")
    put("FingerprintHash", "sha256")
    put("ForwardAgent", "no")
    put("ForwardX11", "no")
    put("ForwardX11Trusted", "no")
    put("GatewayPorts", tunnel.get("gateway_ports", "no"))
    put("GlobalKnownHostsFile", "/dev/null")
    put("HashKnownHosts", "no")
    put("HostbasedAuthentication", "no")
    put("HostKeyAlgorithms", resolve_mapped("host_key_algorithms", tunnel.get("host_key_algorithms"), mappings))
    put("HostKeyAlias", uuid)
    put("HostName", tunnel.get("hostname"))
    put("IdentitiesOnly", "yes")
    put("IdentityAgent", "none")
    put("IdentityFile", identity)
    put("IPQoS", "none")
    put("KbdInteractiveAuthentication", "no")
    put("KexAlgorithms", resolve_mapped("kex_algorithms", tunnel.get("kex_algorithms"), mappings))
    lines.append(
        '    LocalCommand printf "connection: %r@%h:%p\\ntimestamp: `date +%%s`\\n'
        'tunnel_device: %T\\n" > ' + info_file
    )
    put("LocalForward", tunnel.get("local_forward"))
    put("LogLevel", tunnel.get("log_level", "INFO"))
    put("MACs", resolve_mapped("macs", tunnel.get("macs"), mappings))
    put("NoHostAuthenticationForLocalhost", "no")
    put("PasswordAuthentication", "no")
    put("PermitLocalCommand", "yes")
    put("Port", tunnel.get("port") or "22")
    put("PreferredAuthentications", "publickey")
    put(
        "PubkeyAcceptedAlgorithms",
        resolve_mapped("pubkey_accepted_key_types", tunnel.get("pubkey_accepted_key_types"), mappings),
    )
    put("PubkeyAuthentication", "yes")
    put("RekeyLimit", resolve_mapped("rekey_limit", tunnel.get("rekey_limit"), mappings))
    put("RemoteForward", tunnel.get("remote_forward"))
    put("RequestTTY", "no")
    put("ServerAliveCountMax", tunnel.get("server_alive_count_max", "3"))
    put("ServerAliveInterval", tunnel.get("server_alive_interval", "30"))
    put("StreamLocalBindUnlink", "no")
    put("StrictHostKeyChecking", tunnel.get("strict_host_key_checking", "accept-new"))
    put("TCPKeepAlive", tunnel.get("tcp_keep_alive", "yes"))

    tunnel_mode = tunnel.get("tunnel", "no")
    if tunnel_mode and tunnel_mode != "no":
        put("Tunnel", tunnel_mode)
        put("TunnelDevice", tunnel.get("tunnel_device", "any:any"))
    else:
        put("Tunnel", "no")

    put("UpdateHostKeys", tunnel.get("update_host_keys", "yes"))
    put("User", tunnel.get("user"))
    put("UserKnownHostsFile", known_hosts)
    put("VerifyHostKeyDNS", tunnel.get("verify_host_key_dns", "no"))
    put("VisualHostKey", "no")

    return "\n".join(lines) + "\n"


def write_private_key(uuid, key_record):
    """Materialize the base64 private key from config.xml onto disk."""
    identity = os.path.join(STATE_DIR, f"{uuid}.identity")
    known_hosts = os.path.join(STATE_DIR, f"{uuid}.known_hosts")

    material = key_record.get("key_private", "")
    if not material:
        raise AutosshError(f"ssh key for tunnel {uuid} holds no private key material")

    os.makedirs(STATE_DIR, mode=0o700, exist_ok=True)
    os.chmod(STATE_DIR, 0o700)

    decoded = base64.b64decode(material)
    # write via a temporary file so that a running tunnel never observes a
    # partially written identity
    fd, temp_name = tempfile.mkstemp(dir=STATE_DIR)
    try:
        with os.fdopen(fd, "wb") as handle:
            handle.write(decoded)
        os.chmod(temp_name, 0o600)
        os.replace(temp_name, identity)
    except BaseException:
        if os.path.exists(temp_name):
            os.unlink(temp_name)
        raise

    if not os.path.exists(known_hosts):
        with open(known_hosts, "a"):
            pass
        os.chmod(known_hosts, 0o600)


def read_existing_blocks(filename=None):
    """Return {host: block_text} for the currently installed configuration."""
    filename = filename or SSH_CONFIG
    if not os.path.isfile(filename):
        return {}

    blocks = {}
    host = None
    for line in open(filename, "r", encoding="utf-8", errors="replace"):
        match = re.match(r"^Host\s+(\S+)", line)
        if match:
            host = match.group(1)
            blocks[host] = ""
            continue
        if host is not None:
            blocks[host] += line
    return blocks


def block_changed(installed_body, block):
    """Compare an installed block body with a freshly rendered block.

    `installed_body` is what read_existing_blocks() returns: the lines after
    the Host line. `block` is render_tunnel() output, Host line included.

    Blocks are separated by a blank line, so every block read back from the
    installed file except the last carries a trailing newline that a freshly
    rendered block does not. Compare without it, otherwise all but the last
    tunnel count as changed on every Apply.
    """
    def digest(text):
        return hashlib.sha256(text.rstrip("\n").encode("utf-8")).hexdigest()

    return digest(installed_body) != digest(block.split("\n", 1)[1])


def generate():
    """Write the ssh client configuration and identity files.

    Returns a dict describing what changed, so that reconfigure() only
    disturbs the tunnels that actually need it.
    """
    mappings = read_data_model()
    tunnels, keys, interfaces = read_system_config()

    previous = read_existing_blocks()

    content = CONFIG_HEADER
    rendered = {}
    enabled = []
    skipped = []

    for uuid in sorted(tunnels):
        tunnel = tunnels[uuid]
        if tunnel.get("enabled") != "1":
            continue

        key_uuid = tunnel.get("ssh_key", "")
        if key_uuid not in keys:
            log_warn(f"tunnel {uuid} references unknown ssh key '{key_uuid}', skipping")
            skipped.append(uuid)
            continue

        try:
            write_private_key(uuid, keys[key_uuid])
        except (AutosshError, ValueError) as error:
            log_warn(f"tunnel {uuid}: {error}, skipping")
            skipped.append(uuid)
            continue

        block = render_tunnel(uuid, tunnel, mappings, interfaces)
        rendered[uuid] = block
        enabled.append(uuid)
        content += "\n" + block

    os.makedirs(os.path.dirname(SSH_CONFIG), mode=0o750, exist_ok=True)
    fd, temp_name = tempfile.mkstemp(dir=os.path.dirname(SSH_CONFIG))
    try:
        with os.fdopen(fd, "w") as handle:
            handle.write(content)
        os.chmod(temp_name, 0o640)
        os.replace(temp_name, SSH_CONFIG)
    except BaseException:
        if os.path.exists(temp_name):
            os.unlink(temp_name)
        raise

    changed = [
        uuid for uuid, block in rendered.items()
        if uuid not in previous or block_changed(previous[uuid], block)
    ]
    removed = [uuid for uuid in previous if uuid not in rendered]

    # identity material for tunnels that no longer exist has no further use
    for uuid in removed:
        for suffix in (".identity",):
            stale = os.path.join(STATE_DIR, uuid + suffix)
            if os.path.exists(stale):
                os.unlink(stale)

    return {
        "status": "success",
        "message": f"Generated configuration for {len(enabled)} tunnel(s)",
        "data": {
            "enabled": enabled,
            "changed": sorted(changed),
            "removed": sorted(removed),
            "skipped": sorted(skipped),
        },
    }


