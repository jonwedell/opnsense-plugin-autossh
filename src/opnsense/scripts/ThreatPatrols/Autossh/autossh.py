def main():
    parser = argparse.ArgumentParser(description="OPNsense autossh plugin backend")
    sub = parser.add_subparsers(dest="command", required=True)

    sub.add_parser("generate", help="write the ssh client configuration")
    sub.add_parser("reconfigure", help="write the configuration and apply changes")
    sub.add_parser("connection_status", help="report per tunnel status")
    sub.add_parser("version", help="report version information")

    parser_keygen = sub.add_parser("keygen", help="generate an ssh key pair")
    parser_keygen.add_argument("--key-type", required=True)

    parser_hostkeys = sub.add_parser("hostkeys", help="list learned ssh host keys")
    parser_hostkeys.add_argument("--uuid", required=True)

    args = parser.parse_args()

    try:
        if args.command == "generate":
            result = generate()
        elif args.command == "reconfigure":
            result = reconfigure()
        elif args.command == "connection_status":
            result = connection_status()
        elif args.command == "keygen":
            result = keygen(args.key_type)
        elif args.command == "hostkeys":
            result = hostkeys(args.uuid)
        else:
            result = autossh_version()
    except AutosshError as error:
        result = {"status": "failed", "message": str(error)}
    except Exception as error:  # noqa: BLE001 - the UI needs a JSON reply, never a traceback
        log_warn(f"{args.command} failed: {error!r}")
        result = {"status": "failed", "message": f"{type(error).__name__}: {error}"}

    print(json.dumps(result))
    return 0 if result.get("status") == "success" else 1


if __name__ == "__main__":
    sys.exit(main())
