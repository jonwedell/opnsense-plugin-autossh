# configuration sources


def read_data_model(filename=None):
    """Return {field_name: {option_key: algorithm_value}} from the model XML."""
    filename = filename or DATA_MODEL
    if not os.path.isfile(filename):
        raise AutosshError(f"data model not found: {filename}")

    root = ElementTree.parse(filename).getroot()
    tunnel = root.find("./items/tunnels/tunnel")
    if tunnel is None:
        raise AutosshError(f"no tunnel definition found in {filename}")

    mappings = {}
    for field in MAPPED_FIELDS:
        node = tunnel.find(f"./{field}/optionvalues")
        if node is None:
            continue
        mappings[field] = {
            option.tag: (option.get("value") if option.get("value") is not None else option.tag)
            for option in node
        }
    return mappings


def _node_to_dict(node):
    return {child.tag: (child.text or "") for child in node}


def read_system_config(filename=None):
    """Return (tunnels, keys, interfaces) from config.xml."""
    filename = filename or SYSTEM_CONFIG
    if not os.path.isfile(filename):
        raise AutosshError(f"system configuration not found: {filename}")

    root = ElementTree.parse(filename).getroot()

    tunnels = {}
    keys = {}
    section = root.find("./ThreatPatrols/Autossh")
    if section is not None:
        for node in section.findall("./tunnels/tunnel"):
            uuid = node.get("uuid")
            if uuid:
                tunnels[uuid] = _node_to_dict(node)
        for node in section.findall("./keys/key"):
            uuid = node.get("uuid")
            if uuid:
                keys[uuid] = _node_to_dict(node)

    interfaces = {}
    for node in root.findall("./interfaces/*"):
        device = node.find("if")
        if device is not None and device.text:
            interfaces[node.tag] = device.text

    return tunnels, keys, interfaces


