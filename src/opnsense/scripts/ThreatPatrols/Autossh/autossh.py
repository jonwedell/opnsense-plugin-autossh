def pidfile_for(uuid):
    return os.path.join(RUN_DIR, f"autossh.{uuid}.pid")


def daemon_pid(uuid):
    path = pidfile_for(uuid)
    try:
        with open(path, "r") as handle:
            return int(handle.read().strip())
    except (OSError, ValueError):
        return None


def is_running(uuid):
    pid = daemon_pid(uuid)
    if pid is None:
        return False
    try:
        os.kill(pid, 0)
        return True
    except OSError:
        return False


def rc_command(command, uuid=None, timeout=120):
    """Drive the rc script.

    The timeout is deliberate: this runs under configd, so anything that blocks
    here blocks the web request behind it. Degrading to a logged failure beats
    an Apply button that spins forever.
    """
    argv = [RC_SCRIPT, command]
    if uuid is not None:
        argv.append(uuid)

    try:
        result = subprocess.run(
            argv, stdin=subprocess.DEVNULL, capture_output=True, text=True, timeout=timeout
        )
    except subprocess.TimeoutExpired:
        log_warn(f"rc command '{command} {uuid or ''}' timed out after {timeout}s")
        return 1, f"timed out after {timeout}s"

    return result.returncode, (result.stdout or "") + (result.stderr or "")


def reconfigure():
    """Regenerate the configuration and only disturb what changed."""
    outcome = generate()
    data = outcome["data"]
    actions = []

    for uuid in data["removed"] + data["skipped"]:
        if is_running(uuid):
            rc_command("stop_tunnel", uuid)
            actions.append({"uuid": uuid, "action": "stopped"})

    for uuid in data["enabled"]:
        if uuid in data["changed"]:
            if is_running(uuid):
                rc_command("restart_tunnel", uuid)
                actions.append({"uuid": uuid, "action": "restarted"})
            else:
                rc_command("start_tunnel", uuid)
                actions.append({"uuid": uuid, "action": "started"})
        elif not is_running(uuid):
            rc_command("start_tunnel", uuid)
            actions.append({"uuid": uuid, "action": "started"})

    outcome["data"]["actions"] = actions
    outcome["message"] = "{}; {} tunnel(s) adjusted".format(outcome["message"], len(actions))
    return outcome


def process_start_time(pid):
    try:
        result = subprocess.run(
            ["/bin/ps", "-o", "lstart=", "-p", str(pid)],
            capture_output=True, text=True, check=True,
        )
        return result.stdout.strip() or None
    except (OSError, subprocess.CalledProcessError):
        return None


def child_pid(pid):
    """autossh runs as a child of daemon(8); its pid is what the log tags."""
    try:
        result = subprocess.run(
            ["/bin/pgrep", "-P", str(pid)], capture_output=True, text=True
        )
        candidates = [int(v) for v in result.stdout.split()]
        return candidates[0] if candidates else None
    except (OSError, ValueError):
        return None


def last_connection_ok(pid, logfile=None, window=262144):
    """Scan the tail of the log for the most recent 'connection ok' line."""
    logfile = logfile or LOG_FILE
    if pid is None or not os.path.isfile(logfile):
        return None
    try:
        with open(logfile, "rb") as handle:
            handle.seek(0, os.SEEK_END)
            handle.seek(max(0, handle.tell() - window), os.SEEK_SET)
            tail = handle.read().decode("utf-8", errors="replace")
    except OSError:
        return None

    stamp = None
    needle = f"autossh {pid} "
    for line in tail.splitlines():
        if needle in line and "connection ok" in line:
            match = re.search(r"(\d{4}-\d{2}-\d{2}T[\d:.+-]+)", line)
            if match:
                stamp = match.group(1)
    return stamp


def read_info(uuid):
    path = os.path.join(RUN_DIR, f"autossh.{uuid}.info")
    info = {}
    if not os.path.isfile(path):
        return info
    try:
        for line in open(path, "r", encoding="utf-8", errors="replace"):
            if ":" in line:
                field, _, value = line.partition(":")
                info[field.strip()] = value.strip()
    except OSError:
        pass
    return info


def connection_status():
    tunnels, keys, _ = read_system_config()
    rows = []

    for uuid, tunnel in tunnels.items():
        running = is_running(uuid)
        pid = daemon_pid(uuid) if running else None
        autossh_pid = child_pid(pid) if pid else None
        info = read_info(uuid)

        connection = "{}@{}".format(tunnel.get("user", ""), tunnel.get("hostname", ""))
        if tunnel.get("port"):
            connection += ":" + tunnel["port"]

        forwards = [
            ("local", tunnel.get("local_forward")),
            ("remote", tunnel.get("remote_forward")),
            ("dynamic", tunnel.get("dynamic_forward")),
        ]

        rows.append({
            "uuid": uuid,
            "enabled": tunnel.get("enabled", "0"),
            "description": tunnel.get("description", ""),
            "connection": connection,
            "ssh_key": keys.get(tunnel.get("ssh_key", ""), {}).get("name", ""),
            "bind_interface": tunnel.get("bind_interface", ""),
            "forwards": ", ".join(f"{label}: {value}" for label, value in forwards if value),
            "status": "running" if running else "stopped",
            "pid": pid,
            "started": process_start_time(pid) if pid else None,
            "last_ok": last_connection_ok(autossh_pid),
            # ssh expands %T to the literal "NONE" when no tunnel was requested
            "tunnel_device": info.get("tunnel_device") if info.get("tunnel_device") != "NONE" else None,
        })

    rows.sort(key=lambda row: (row["description"] or row["connection"]).lower())
    return {
        "status": "success",
        "message": f"Collected status for {len(rows)} tunnel(s)",
        "total": len(rows),
        "rows": rows,
    }


