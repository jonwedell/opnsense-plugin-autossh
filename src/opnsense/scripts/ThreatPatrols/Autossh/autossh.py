# Algorithm fields. These normally hold algorithm names directly, because
# BaseModel keys an option list by the `value` attribute when one is present
# (see the note in Autossh.xml). The element-name placeholders are only ever
# seen in configurations written by the original plugin's 0.3.0 migration,
# which stored them by mistake; resolve_mapped() accepts either spelling so
# such a configuration still renders correctly.
MAPPED_FIELDS = (
    "ciphers",
    "host_key_algorithms",
    "kex_algorithms",
    "macs",
    "pubkey_accepted_key_types",
    "rekey_limit",
)

CONFIG_HEADER = """#
# {path}
#
# This file is automatically generated from config.xml by the OPNsense autossh
# plugin. Manual changes *will* be lost on the next Apply.
#
# Each Host block is named after the tunnel UUID in config.xml.
# Reference: ssh_config(5)
#
""".format(path=SSH_CONFIG)


class AutosshError(Exception):
    pass


def find_binary(name):
    """autossh pulls in openssh-portable, but fall back to base if need be."""
    for prefix in ("/usr/local/bin", "/usr/bin"):
        candidate = os.path.join(prefix, name)
        if os.path.exists(candidate):
            return candidate
    return os.path.join("/usr/local/bin", name)


def log_warn(message):
    syslog.openlog("autossh", logoption=syslog.LOG_PID, facility=syslog.LOG_DAEMON)
    syslog.syslog(syslog.LOG_WARNING, message)
    print(f"warning: {message}", file=sys.stderr)


