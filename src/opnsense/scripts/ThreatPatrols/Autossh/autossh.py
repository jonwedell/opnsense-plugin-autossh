# key material


KEY_GENERATORS = {
    "ecdsa256": ["-t", "ecdsa", "-b", "256"],
    "ecdsa384": ["-t", "ecdsa", "-b", "384"],
    "ecdsa521": ["-t", "ecdsa", "-b", "521"],
    "ed25519": ["-t", "ed25519"],
    "rsa2048": ["-t", "rsa", "-b", "2048"],
    "rsa4096": ["-t", "rsa", "-b", "4096"],
}


def system_hostid():
    try:
        with open("/etc/hostid", "r") as handle:
            return handle.read().strip()
    except OSError:
        return "unknown"


def keygen(key_type):
    if key_type not in KEY_GENERATORS:
        raise AutosshError(f"unsupported key type '{key_type}'")

    ssh_keygen = find_binary("ssh-keygen")
    workdir = tempfile.mkdtemp(prefix="autossh-keygen.")
    keyfile = os.path.join(workdir, "key")
    try:
        subprocess.run(
            [ssh_keygen] + KEY_GENERATORS[key_type]
            + ["-q", "-N", "", "-f", keyfile, "-C", f"host_id:{system_hostid()}"],
            capture_output=True, text=True, check=True,
        )
        fingerprint = subprocess.run(
            [ssh_keygen, "-l", "-E", "sha256", "-f", keyfile + ".pub"],
            capture_output=True, text=True, check=True,
        ).stdout.strip()

        with open(keyfile, "rb") as handle:
            private = handle.read()
        with open(keyfile + ".pub", "rb") as handle:
            public = handle.read()
    except subprocess.CalledProcessError as error:
        raise AutosshError(f"ssh-keygen failed: {error.stderr.strip() or error}") from error
    finally:
        for name in (keyfile, keyfile + ".pub"):
            if os.path.exists(name):
                os.unlink(name)
        os.rmdir(workdir)

    return {
        "status": "success",
        "message": "SSH key pair successfully created",
        "data": {
            "key_private": base64.b64encode(private).decode("utf8"),
            "key_public": base64.b64encode(public).decode("utf8"),
            "key_fingerprint": fingerprint,
            "timestamp": str(int(time.time())),
        },
    }


def hostkeys(uuid):
    path = os.path.join(STATE_DIR, f"{uuid}.known_hosts")
    if not os.path.isfile(path):
        return {
            "status": "failed",
            "message": "No known hosts recorded yet; start the tunnel once to learn the host key.",
            "data": [],
        }

    entries = []
    for line in open(path, "r", encoding="utf-8", errors="replace"):
        parts = line.split()
        if len(parts) >= 3:
            # drop the hostname/alias field, keep algorithm + key (+ comment)
            entries.append(" ".join(parts[1:]))

    return {
        "status": "success",
        "message": f"Found {len(entries)} host key(s)",
        "data": entries,
    }


def autossh_version():
    try:
        result = subprocess.run(
            [find_binary("autossh"), "-V"], capture_output=True, text=True
        )
        binary = (result.stdout or result.stderr).strip().splitlines()
        binary = binary[0] if binary else "unknown"
    except OSError:
        binary = "not installed"

    return {
        "status": "success",
        "message": "autossh version information",
        "data": {"plugin": __version__, "autossh": binary},
    }


